        <h1 class="page-info-titre">Données personnelles</h1>

        <h2>Données collectées</h2>
        <p>Pour chaque membre : nom, prénom, adresse email, téléphone (facultatif), commentaire interne (facultatif) et historique des emprunts. Le mot de passe n'est jamais stocké en clair : seule une empreinte chiffrée (hash) est conservée.</p>

        <h2>Pourquoi ces données ?</h2>
        <p>Uniquement pour gérer les prêts de matériel : savoir qui a emprunté quel équipement, sur quelle période, et pouvoir contacter l'emprunteur. Aucune donnée n'est vendue ni transmise à des tiers.</p>

        <h2>Qui y a accès ?</h2>
        <p>Le service technique (administrateurs) voit la liste des membres et des emprunts. Un emprunteur ne voit que ses propres demandes.</p>

        <h2>Durée de conservation</h2>
        <p>Les données sont conservées tant que le compte est actif, puis supprimées ou anonymisées lorsque la personne quitte l'établissement.</p>

        <h2>Vos droits</h2>
        <p>Conformément au RGPD, vous pouvez demander à consulter, corriger ou supprimer vos données, via la page <a href="/page/contact">Contact</a>. En cas de difficulté, vous pouvez saisir la CNIL (cnil.fr).</p>

        <h2>Cookies</h2>
        <p>LOC MNS utilise uniquement un cookie de session, indispensable pour rester connecté. Il est supprimé à la déconnexion ou à la fermeture du navigateur.</p>

